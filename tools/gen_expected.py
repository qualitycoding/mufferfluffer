#!/usr/bin/env python3
"""Planner tool: writes tests/core/expected_effects.inc (FROZEN) from tests/fixtures/effects.json.
The frozen C++ tests compare the core's tables with this independent rendering of the fixture.
usage: gen_expected.py <effects.json> <expected_effects.inc>   |   gen_expected.py --check <json> <inc>"""
import json, sys
def fmt(x):
    s = repr(float(x)); return s + ("f" if ("." in s or "e" in s) else ".0f")
def q(s): return "nullptr" if s is None else '"' + s + '"'
def render(doc):
    T = {"linear": 0, "log": 1, "stepped": 2}; K = {"audio": 0, "cv_normalised": 1, "cv_volt_per_oct": 2, "trigger": 3}
    o = ["// FROZEN - DO NOT MODIFY. Generated by tools/gen_expected.py from tests/fixtures/effects.json.",
         "struct XParam { const char* id; const char* name; const char* unit; float min, max, def; int taper; int numSteps; const char* steps[12]; };",
         "struct XPort { const char* id; const char* name; int kind; const char* param; float depth; };",
         "struct XEffect { int id; const char* slug; const char* name; int milestone; int numParams; XParam params[20]; int numInputs; XPort inputs[8]; int numOutputs; XPort outputs[3]; int numMeters; const char* meters[3]; const char* rightOutput; bool monoSumsRight; };",
         "static const XEffect kExpected[7] = {"]
    for e in doc["effects"]:
        o.append(f"  {{ {e['id']}, {q(e['slug'])}, {q(e['name'])}, {e['milestone']}, {len(e['params'])}, {{")
        for p in e["params"]:
            steps = p.get("steps", [])
            o.append(f"      {{ {q(p['id'])}, {q(p['name'])}, {q(p['unit'])}, {fmt(p['min'])}, {fmt(p['max'])}, {fmt(p['def'])}, {T[p['taper']]}, {len(steps)}, {{ {', '.join(q(s) for s in steps)} }} }},")
        o.append("    },")
        for key in ("inputs", "outputs"):
            o.append(f"    {len(e[key])}, {{ " + ", ".join(f"{{ {q(x['id'])}, {q(x['name'])}, {K[x['kind']]}, {q(x['param'])}, {fmt(x['depth'])} }}" for x in e[key]) + " },")
        o.append(f"    {len(e['meters'])}, {{ " + ", ".join(q(m["id"]) for m in e["meters"]) + f" }}, {q(e['right_output'])}, {'true' if e['mono_sums_right'] else 'false'} }},")
    o.append("};")
    o.append("static const char* const kExpectedPatterns[24][8] = {")
    for p in doc["patterns"]:
        o.append("  { " + ", ".join(q(c) for c in p["channels"]) + " },")
    o.append("};")
    return "\n".join(o) + "\n"
if sys.argv[1] == "--check":
    sys.exit(0 if open(sys.argv[3]).read() == render(json.load(open(sys.argv[2]))) else 1)
open(sys.argv[2], "w").write(render(json.load(open(sys.argv[1]))))
