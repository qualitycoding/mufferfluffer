#!/usr/bin/env python3
"""Generates the C++ description tables of the DSP core from tests/fixtures/effects.json.
usage: gen_tables.py <effects.json> <output.inc>
Every number is formatted by one function (fmt) so that the output is always a valid float literal."""
import json, sys

def fmt(x):
    s = repr(float(x))
    if "e" in s or "E" in s or "." in s: return s + "f"
    return s + ".0f"
def cstr(s): return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

doc = json.load(open(sys.argv[1]))
TAPER = {"linear": "Taper::Linear", "log": "Taper::Log", "stepped": "Taper::Stepped"}
KIND = {"audio": "PortKind::Audio", "cv_normalised": "PortKind::CvNormalised", "cv_volt_per_oct": "PortKind::CvVoltPerOct", "trigger": "PortKind::Trigger"}
o = ["// GENERATED by tools/gen_tables.py from tests/fixtures/effects.json - do not edit by hand.", ""]
for e in doc["effects"]:
    n = e["enum"]; pid = [p["id"] for p in e["params"]]
    for p in e["params"]:
        if p["taper"] == "stepped":
            o.append(f"static const char* const k{n}_{p['id']}_steps[] = {{ " + ", ".join(cstr(s) for s in p["steps"]) + " };")
    o.append(f"static const ParamSpec k{n}Params[] = {{")
    for p in e["params"]:
        st = p["taper"] == "stepped"
        o.append(f"    {{ {cstr(p['id'])}, {cstr(p['name'])}, {cstr(p['unit'])}, {fmt(p['min'])}, {fmt(p['max'])}, {fmt(p['def'])}, {TAPER[p['taper']]}, {len(p['steps']) if st else 0}, {('k%s_%s_steps' % (n, p['id'])) if st else 'nullptr'} }},")
    o.append("};")
    for key in ("inputs", "outputs"):
        o.append(f"static const PortSpec k{n}{key.capitalize()}[] = {{")
        for q in e[key]:
            o.append(f"    {{ {cstr(q['id'])}, {cstr(q['name'])}, {KIND[q['kind']]}, {pid.index(q['param']) if q['param'] else -1}, {fmt(q['depth'])} }},")
        o.append("};")
    o.append(f"static const MeterSpec k{n}Meters[] = {{ " + ", ".join(f"{{ {cstr(m['id'])}, {cstr(m['name'])} }}" for m in e["meters"]) + " };")
o.append("static const EffectInfo kEffectInfos[] = {")
for e in doc["effects"]:
    n = e["enum"]; outs = [q["id"] for q in e["outputs"]]
    ro = outs.index(e["right_output"]) if e["right_output"] else -1
    o.append(f"    {{ EffectId::{n}, {cstr(e['slug'])}, {cstr(e['name'])}, {len(e['params'])}, k{n}Params, {len(e['inputs'])}, k{n}Inputs, {len(e['outputs'])}, k{n}Outputs, {len(e['meters'])}, k{n}Meters, {ro}, {'true' if e['mono_sums_right'] else 'false'} }},")
o.append("};")
# filter-bank patterns: per pattern, per channel: length and a 64-bit trigger mask (bit s set = trigger on step s); length 0 = static
o.append("struct PatternChannel { int length; unsigned long long mask; };")
o.append(f"static const PatternChannel kPatterns[{len(doc['patterns'])}][8] = {{")
for p in doc["patterns"]:
    cells = []
    for ch in p["channels"]:
        if ch == "-": cells.append("{ 0, 0ULL }")
        else:
            assert 1 <= len(ch) <= 64 and set(ch) <= {"x", "."}
            cells.append(f"{{ {len(ch)}, 0x{sum(1 << i for i, c in enumerate(ch) if c == 'x'):X}ULL }}")
    o.append("    { " + ", ".join(cells) + " },  // " + p["bank"] + " " + str(p["index"] + 1) + " " + p["name"])
o.append("};")
open(sys.argv[2], "w").write("\n".join(o) + "\n")
